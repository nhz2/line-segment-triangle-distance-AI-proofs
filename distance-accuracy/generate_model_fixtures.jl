# Regenerate raw-bit fixtures from the Julia implementation. The independent
# Lean IEEE model checks these at runtime; these are regression tests, not proofs.
using SimplexCellLists, StaticArrays
const destination = joinpath(@__DIR__, "ModelFixtures.lean")
const origin = SA[0,0,0]
const cases = [
    ("point-point", [origin], [SA[1,2,3]]),
    ("point-segment", [SA[0,1,0]], [SA[-1,0,0],SA[1,0,0]]),
    ("point-triangle", [SA[0,0,1]], [SA[-1,-1,0],SA[1,-1,0],SA[0,1,0]]),
    ("segment-segment", [SA[-1,0,0],SA[1,0,0]], [SA[0,-1,1],SA[0,1,1]]),
    ("segment-triangle", [SA[0,0,-1],SA[0,0,1]], [SA[-1,-1,0],SA[1,-1,0],SA[0,1,0]]),
    ("triangle-triangle", [SA[-1,-1,0],SA[1,-1,0],SA[0,1,0]], [SA[-1,0,-1],SA[1,0,-1],SA[0,0,1]]),
    ("repeated-points", [origin,origin,origin], [SA[1,2,3],SA[1,2,3],SA[1,2,3]]),
    ("collinear", [SA[-1,0,0],origin,SA[1,0,0]], [SA[0,-1,0],origin,SA[0,1,0]]),
    ("parallel-segments", [origin,SA[1,1,1]], [SA[1,0,0],SA[2,1,1]]),
    ("large-error", [SA[-9373420,-7754638,-8416905],SA[9778836,10196786,10057847]],
        [SA[-10350544,-10332076,-10169968],SA[10350545,7004759,9067019],SA[9871916,10332077,10169969]])
]
word(x::Float32) = string(reinterpret(UInt32,x))
word(x::Float64) = string(reinterpret(UInt64,x))
vec(x) = "![" * join(word.(x),", ") * "]"
function simplex(xs)
    tag=("point","segment","triangle")[length(xs)]
    ".$tag " * (length(xs)==1 ? "("*vec(xs[1])*")" : "!["*join(vec.(xs),", ")*"]")
end
open(destination,"w") do io
    println(io,"-- Generated by generate_model_fixtures.jl; regression tests, not accuracy proofs.")
    println(io,"import DistanceAccuracy.IEEEAlgorithm\nnamespace DistanceAccuracy.ModelFixtures")
    println(io,"open FP.IEEE FP.IEEE.Interchange IEEEAlgorithm")
    println(io,"structure Fixture (I : Interchange) where\n  label : String\n  x : Simplex I\n  y : Simplex I\n  q : I.Word\n  r : Vec3 I\n  s : Weights I\n  t : Weights I")
    for (T,fmt) in ((Float32,"fp32"),(Float64,"fp64"))
        println(io,"def fixtures_",fmt," : List (Fixture ",fmt,") := [")
        entries=String[]
        for (name,left,right) in cases, swapped in (false,true)
            x=map(v->T.(v),swapped ? right : left);y=map(v->T.(v),swapped ? left : right)
            result=dist_sqr_r_s_t(SVector{length(x)}(Tuple(x)),SVector{length(y)}(Tuple(y)));q,r,s,t=result
            padded(v)=SA[length(v)>0 ? v[1] : zero(T),length(v)>1 ? v[2] : zero(T)]
            label=name*(swapped ? "-reversed" : "")
            push!(entries,"  ⟨\"$label\", $(simplex(x)), $(simplex(y)), $(word(q)), $(vec(r)), $(vec(padded(s))), $(vec(padded(t)))⟩")
        end
        # Underflow and zero-length division cases, without NaN payload choices.
        tiny=T(2)^(-120*(T==Float32)-1000*(T==Float64))
        x=SA[SA[tiny,tiny,tiny]];y=SA[zero(x[1]),zero(x[1]),zero(x[1])]
        q,r,s,t=dist_sqr_r_s_t(x,y)
        push!(entries,"  ⟨\"subnormal-products\", $(simplex(x)), $(simplex(y)), $(word(q)), $(vec(r)), $(vec(SA[zero(T),zero(T)])), $(vec(t))⟩")
        println(io,join(entries,",\n"),"]")
    end
    println(io,"""
def checkFixture (I : Interchange) [I.Valid] (f : Fixture I) : IO Unit := do
  let got := evaluate I f.x f.y
  if got.q != f.q || !(List.finRange 3).all (fun k => got.r k == f.r k) ||
      !(List.finRange 2).all (fun k => got.left k == f.s k && got.right k == f.t k) then
    throw (IO.userError ("IEEE model disagrees with Julia: " ++ f.label))
#eval do
  fixtures_fp32.forM (checkFixture fp32)
  fixtures_fp64.forM (checkFixture fp64)
  IO.println "42 IEEE model fixtures agree bit-for-bit with Julia (q, r, and weights)."
end DistanceAccuracy.ModelFixtures
""")
end
println("Wrote ",destination)
