using SimplexCellLists, StaticArrays, LinearAlgebra, Test, SHA
const R = Rational{BigInt}
const examples = (
    (Float32,
     ((10153498,-9742366,-10040702),(-7790188,9455320,8348288)),
     ((-10309259,10312324,10167788),(6967535,-10312324,-9063049),(10309259,-9837480,-10167787)),
     9415//1000,9416//1000),
    (Float64,
     ((-5305399339007970,-4197878618699932,-4564727400136850),(4977993621024429,5474911713697635,5399940106562222)),
     ((-5552362190545168,-5546991333408768,-5459960263606271),(5552362190545168,3761752207528962,4726806124953601),(5021360885063409,5546991333408768,5459960263606272)),
     9185//1000,9186//1000))
leanrat(x) = "($(numerator(x)) / $(denominator(x)))"
leanvec(v) = "!["*join(v,", ")*"]"
word(x::Float32)=string(reinterpret(UInt32,x))
word(x::Float64)=string(reinterpret(UInt64,x))
function check_example(example,io)
    T,xx,yy,lo,hi=example
    x=map(v->SVector{3,T}(v),SVector(xx));y=map(v->SVector{3,T}(v),SVector(yy))
    xr=map(v->R.(v),x);yr=map(v->R.(v),y)
    @test all(Tuple(R.(x[i]))==R.(xx[i]) for i in 1:2)
    @test all(Tuple(R.(y[i]))==R.(yy[i]) for i in 1:3)
    P=xr[2]-xr[1];E=yr[2]-yr[1];F=yr[3]-yr[1];offset=yr[1]-xr[1]
    N=cross(E,F);den=dot(N,P)
    t=dot(N,offset)/den
    u=dot(cross(F,offset),P)/den
    v=dot(cross(offset,E),P)/den
    @test 0<t<1 && 0<u && 0<v && u+v<1
    @test xr[1]+t*P == yr[1]+u*E+v*F  # exact intersection, hence d=0
    q,sep,s,weights=dist_sqr_r_s_t(x,y)
    ell=maximum(v->maximum(abs,v),(xr...,yr...))
    unit=R(eps(T))*ell
    @test (R(lo)*unit)^2 < R(q) < (R(hi)*unit)^2
    floor_upper=T==Float32 ? BigInt(1)//BigInt(2)^31 : BigInt(1)//BigInt(2)^255
    @test (R(lo)*unit+floor_upper)^2 < R(q)
    # Power-of-two rescaling gives the same example at coordinate scale < 1.
    power=T==Float32 ? -24 : -53
    scale=T(2)^power
    qscaled=dist_sqr_r_s_t(map(p->scale*p,x),map(p->scale*p,y))[1]
    @test R(qscaled)==R(q)*R(scale)^2
    println(T," exact d=0; ell=",ell,"; q=",R(q),"; q bits=",word(q))
    setprecision(256) do
        println("sqrt(q)=",sqrt(BigFloat(q)))
        println("error/(eps*ell)=",sqrt(BigFloat(q))/BigFloat(unit))
    end
    println("exact segment parameter=",t,"; triangle weights=",(1-u-v,u,v))
    println("x=",xx,"\ny=",yy)
    io===nothing && return
    fmt=T==Float32 ? "fp32" : "fp64"
    name=T==Float32 ? "binary32" : "binary64"
    println(io,"namespace $name\nabbrev V := Fin 3 → ℝ")
    for (label,point) in zip(("P0","P1","A","B","C"),(xx...,yy...))
        println(io,"def $label : V := ",leanvec(string.(point)))
    end
    println(io,"noncomputable def t : ℝ := ",leanrat(t))
    println(io,"noncomputable def u : ℝ := ",leanrat(u))
    println(io,"noncomputable def v : ℝ := ",leanrat(v))
    println(io,"lemma intersection : P0+t•(P1-P0)=A+u•(B-A)+v•(C-A) := by\n  funext i\n  fin_cases i <;> norm_num [P0,P1,A,B,C,t,u,v]")
    println(io,"lemma convex_parameters : 0<t ∧ t<1 ∧ 0<u ∧ 0<v ∧ u+v<1 := by norm_num [t,u,v]")
    println(io,"noncomputable def q : ℝ := ",leanrat(R(q)))
    println(io,"noncomputable def unit : ℝ := ",leanrat(unit))
    println(io,"lemma coefficient_interval : $(leanrat(lo))*unit < Real.sqrt q ∧ Real.sqrt q < $(leanrat(hi))*unit := by\n  have hq := Real.sq_sqrt (show 0≤q by norm_num [q])\n  have hn := Real.sqrt_nonneg q\n  have hlo : ($(leanrat(lo))*unit)^2 < q := by norm_num [q,unit]\n  have hhi : q < ($(leanrat(hi))*unit)^2 := by norm_num [q,unit]\n  have hu : 0<unit := by norm_num [unit]\n  constructor <;> nlinarith")
    xword="!["*join((leanvec(word.(p)) for p in x),", ")*"]"
    yword="!["*join((leanvec(word.(p)) for p in y),", ")*"]"
    println(io,"def xw : IEEEAlgorithm.Segment $fmt := $xword\ndef yw : IEEEAlgorithm.Triangle $fmt := $yword")
    println(io,"#eval do\n  let got := InvMultiplyAlgorithm.segmentTriangle $fmt xw yw\n  if got.q != $(word(q)) then throw (IO.userError \"$name IEEE output mismatch\")\n  IO.println \"$name IEEE squared-distance word of the model matches Julia.\"")
    println(io,"#print axioms intersection\n#print axioms convex_parameters\n#print axioms coefficient_interval\nend $name")
end
function main()
    src=joinpath(dirname(pathof(SimplexCellLists)),"distances.jl")
    println("source=",src,"\nsha256=",bytes2hex(sha256(read(src))))
    dest="--generate-lean" in ARGS ? joinpath(@__DIR__,"RoundingExamples.lean") : nothing
    io=dest===nothing ? nothing : open(dest,"w")
    try
        if io!==nothing
            println(io,"-- Generated by rounding_examples.jl --generate-lean.\n-- Geometry and error comparisons are kernel-checked; IEEE output is a runtime fixture.\nimport DistanceAccuracy.InvMultiplyFinal\nnamespace DistanceAccuracy.RoundingExamples\nopen FP.IEEE FP.IEEE.Interchange\nset_option maxRecDepth 10000\nset_option maxHeartbeats 2000000")
        end
        foreach(ex->check_example(ex,io),examples)
        io!==nothing && println(io,"end DistanceAccuracy.RoundingExamples")
    finally
        io!==nothing && close(io)
    end
    println("All exact intersection, output-error, and rescaling checks passed.")
end
main()
